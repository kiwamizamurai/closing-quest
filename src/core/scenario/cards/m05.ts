const reportCheck = (() => {
  const sales = MONTHLY_SALES[0] ?? 0;
  const cogs = (MONTH_END_INVENTORY[-1] ?? 0) + purchasesOf(sales) - (MONTH_END_INVENTORY[0] ?? 0);
  const wrongCogs = 8_140_000;
  return routine({
    id: 'c05_report_check',
    kind: 'AUDIT',
    title: '月次報告の資料を、試算表と照合する',
    date: mkDate(1, 11),
    skill: 'audit',
    situation:
      '4月の月次報告の資料を、Excel で作りました。社長に出す前に、会計システムの試算表の数字と一致しているかを確認します。',
    questions: [
      pick(
        '試算表と、報告資料の数字が一致していない行を、すべて選んでください。',
        {
          caption: '4月の数字（税抜）',
          headers: ['項目', '試算表', '報告資料（Excel）'],
          rows: [
            ['売上高', sales, sales],
            ['売上原価', cogs, wrongCogs],
            ['売上総利益', sales - cogs, sales - wrongCogs],
          ],
          numericColumns: [1, 2],
        },
        [1, 2],
        '3 行を、試算表と報告資料で見比べます。',
        '原因は、売上原価の転記ミス（数字の入れ替え）です。売上総利益は、売上高から売上原価を引いて出す数字なので、売上原価が違うと連鎖してずれます。資料を出す前に、元の試算表と 1 行ずつ照らします。',
      ),
    ],
    sources: [SRC_YAYOI, SRC_MF, SRC_FASS],
    keywords: ['月次報告', '試算表', '数字の整合'],
    summary: '報告資料の数字を、会計システムの試算表と 1 行ずつ照らして、転記ミスを直す。',
    squareLabel: '報告資料',
  });
})();

